% =====================
% Cargar datos medidos
% =====================
t = data(:,1)/1000;   % ms -> s
theta = data(:,2);

% Tiempo de muestreo
Ts = mean(diff(t));

% =====================
% Entrada (escalón)
% =====================
thetaFinal = max(theta);
u = ones(size(t)) * thetaFinal;

% =====================
% Visualizar datos
% =====================
figure;
stairs(t, theta, 'b', 'LineWidth', 1.5);
xlabel('Tiempo [s]');
ylabel('\theta [°]');
title('Respuesta al escalón medida');
grid on;

% =====================
% Identificación
% =====================
iddata_sys = iddata(theta, u, Ts);

% Modelo de 1er orden
sys1 = tfest(iddata_sys, 1, 0);
sys1 = sys1 / dcgain(sys1);

% Modelo de 2º orden
sys2 = tfest(iddata_sys, 2, 0);
sys2 = sys2 / dcgain(sys2);

disp('--- Modelo 1er orden (ganancia normalizada a 1) ---');
sys1
disp('--- Modelo 2º orden (ganancia normalizada a 1) ---');
sys2

% Comparación
figure;
compare(iddata_sys, sys1, sys2);

